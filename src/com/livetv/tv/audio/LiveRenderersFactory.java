package com.livetv.tv.audio;

import android.content.Context;
import android.os.Handler;

import androidx.media3.common.util.UnstableApi;
import androidx.media3.exoplayer.DefaultRenderersFactory;
import androidx.media3.exoplayer.Renderer;
import androidx.media3.exoplayer.audio.AudioRendererEventListener;
import androidx.media3.exoplayer.audio.AudioSink;
import androidx.media3.exoplayer.mediacodec.MediaCodecSelector;

import java.util.ArrayList;

/**
 * The renderers of LiveTV's players: ExoPlayer's, plus {@link Mp2AudioRenderer} for the MP2 audio
 * that the TV cannot decode.
 */
@UnstableApi
public final class LiveRenderersFactory extends DefaultRenderersFactory {

    public LiveRenderersFactory(Context context) {
        super(context);
    }

    @Override
    protected void buildAudioRenderers(
            Context context,
            @ExtensionRendererMode int extensionRendererMode,
            MediaCodecSelector mediaCodecSelector,
            boolean enableDecoderFallback,
            AudioSink audioSink,
            Handler eventHandler,
            AudioRendererEventListener eventListener,
            ArrayList<Renderer> out) {
        super.buildAudioRenderers(
                context,
                extensionRendererMode,
                mediaCodecSelector,
                enableDecoderFallback,
                audioSink,
                eventHandler,
                eventListener,
                out);
        // Last: when the TV has its own MP2 decoder, its renderer comes first and is chosen.
        out.add(new Mp2AudioRenderer(eventHandler, eventListener, audioSink));
    }
}
